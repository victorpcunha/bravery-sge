export function getCampoAmigavel(campo: string): string {
  return CAMPO_AMIGAVEL[campo] ?? campo
}

export function getDescricaoValor(campo: string, valor: string | null | undefined): string | null {
  if (!valor) return null
  const descricoes = VALOR_DESCRICOES[campo]
  if (!descricoes) return null
  return descricoes[valor] ?? null
}

export function getAbaEscola(campo: string): AbaEscola | null {
  return CAMPO_ABA_ESCOLA[campo] ?? null
}

const CODES_EM_MENSAGEM = /deve ser ([\d\s,]+?)(?:ou (\d+))?\.$/i

function substituirCampoNaMensagem(campo: string, mensagem: string): string {
  const label = CAMPO_AMIGAVEL[campo]
  if (!label || campo.length < 5) return mensagem
  const esc = campo.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return mensagem.replace(new RegExp(`\\b${esc}\\b`, 'g'), label.toLowerCase())
}

export function gerarMensagemAmigavel(campo: string, mensagem: string): string {
  let msg = mensagem

  // 1. Substitui listas de códigos por descrições (ex: "Deve ser 1, 2, 3, 7 ou 8.")
  const descricoes = VALOR_DESCRICOES[campo]
  if (descricoes) {
    const match = msg.match(CODES_EM_MENSAGEM)
    if (match) {
      const itens = match[1]
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
      if (match[2]) itens.push(match[2])
      const descritos = itens.map((cod) => {
        const desc = descricoes[cod]
        return desc ? `${desc} (${cod})` : cod
      })
      if (descritos.length > 0) {
        const lista = descritos.slice(0, -1).join(', ') + (descritos.length > 1 ? ' ou ' : '') + descritos[descritos.length - 1]
        msg = msg.replace(CODES_EM_MENSAGEM, 'deve ser ' + lista + '.')
      }
    }
  }

  // 2. Substitui o nome técnico do campo da regra dentro da mensagem
  //    (ex: "qtd_salas_fora é obrigatório..." → "Quantidade de salas fora do prédio é obrigatório...")
  msg = substituirCampoNaMensagem(campo, msg)

  return msg.charAt(0).toUpperCase() + msg.slice(1)
}